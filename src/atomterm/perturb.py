"""Perturbation theory: the PT2 analyzation over a CAS state.

PURPOSE
-------
Second-order correction E(2) on top of a certified CAS state -- the
dynamic-correlation axis the term tables do not carry. The analyzation
is the WINDOW-LADDER diagnostic: the same construction applied to
every window of a campaign ladder reads whether the ladder's CAS
spread is dynamic correlation the external space supplies (the
corrected ladder flattens) or genuinely static (it keeps the spread).

The variants form a ladder of ZEROth-order Hamiltonian choices from
simplest up; everything else is shared:

*   **Epstein-Nesbet (EN)**: ``H0`` is the diagonal of the exact H in
    the configuration basis -- denominators are exact configuration
    energies ``H_mu_mu``. The most literal partition, and the
    intruder-prone one: nothing forbids ``E0 - H_mu_mu ~ 0``.
*   **Moller-Plesset (MP)**: ``H0`` is the Fock diagonal --
    denominators are orbital-gap sums. Intruder-safe for one
    reference; undefined for a CAS without a range separation.
*   **Dyall**: the multi-reference MP: a Fock-type ``H0`` with the
    orbital space split inactive/active/virtual, the active orbitals
    entering the mean field through their average occupations;
    canonical orbital energies in all three ranges. External
    denominators are orbital-gap sums (sign-definite); the
    empty-active limit is exact MP2.
*   **NEVPT2**: Dyall's ``H0`` plus strong contraction -- the FOIS
    grouped into the 7 excitation classes
    (``[1V][2V][3V][4V][V][W][X]``), each one small linear solve on
    the density cumulants (connected RDM parts, up to the 4-cumulant).
    Parameter-free; intruder-free by theorem (the floors VERIFY it);
    strictly size-consistent. The diagnostic's keyed read.
*   **CASPT2** (specified, not built here): a Fock-type ``H0`` from
    the full transition density plus INTERNAL contraction (the FOIS
    generated by applying H to the reference CSFs). The contracted
    space makes ``H0`` non-diagonal -- no sum-over-states formula --
    and structurally intruder-prone, handled by the level shift and
    the IPEA shift: empirical dials that move energies by tens of
    mEh and mask exactly the intruder information the floors read.

Shared vocabulary:

*   **FOIS** -- first-order interacting space: the configurations the
    exact H couples to from the reference. In determinant form:
    determinants differing from a reference determinant in at most
    two spin-orbitals (the Slater-Condon reach). An operator of the
    (one-body, two-body) form connects exactly those and no others.
*   **Intruder state** -- an external configuration with
    ``E0 - H0_mu_mu ~ 0``: the failure mode of exact-diagonal
    partitions, read through the floor meter.
*   **Size-consistency** -- ``E(A...B) = E(A) + E(B)`` at infinite
    separation; the property protecting ladder comparisons.
*   **Strong vs internal contraction** -- determinant grouping into
    class spaces (NEVPT2) vs reference-generated configurations
    (CASPT2): the FOIS-realization axis of the ladder.

Conventions
-----------
*   Pure NumPy plus detbasis: the module consumes the operator pair
    ``(h1, g)`` over the VALENCE space (the folded-core field already
    in ``h1``; see ``operators.active_space_integrals`` -- the same
    folding at any column set) and a CI vector in detbasis order over
    the ACTIVE-first CAS. No pyscf import here.
*   Valence columns are ACTIVE-FIRST: positions ``0..n_act-1`` are
    the active space, ``n_act..n_val-1`` the external space; the CAS
    determinant set follows (every occupied spin-orbital inside the
    active columns).
*   The folded core is PT2-frozen: no core orbital is ever excited --
    core orbitals do not exist in the valence space; the correction
    measures the dynamic correlation ABOVE the folded field.
*   Determinants, spin-orbital and tensor conventions follow detbasis
    (sorted-tuple determinants; physicist two-body tensor).
*   Real operators stay real; the result dtype follows the inputs.

Meters (the honesty surface)
----------------------------
*   ``floor`` -- ``min |E0 - H0_mu_mu|`` over the COUPLED FOIS (an
    uncoupled determinant has zero numerator; its denominator is
    irrelevant). The intruder surface: small floor = the partition
    struggles; the coupling-aware EN floors are themselves signal.
*   ``w_ref`` -- ``1 / (1 + sum |C1_mu|^2)``: the reference weight in
    the first-order-corrected wavefunction; the expansion-quality
    gate (below ~0.8 conventionally suspect).

Layering
--------
rung 0: :func:`fois_indices` (the brute coupling-set enumeration, the
completeness certificate) and the apply-pattern enumeration inside
:func:`epstein_nesbet` (the exact nonzero pattern, measured against
the brute one on generic inputs).
rung 1: :func:`epstein_nesbet` (production: matrix-free couplings +
:func:`diagonal_energies`) beside :func:`epstein_nesbet_dense` (the
dense Slater-Condon slice -- the elementwise twin).
rungs 2-3 (Dyall, NEVPT2-SC) join this ladder under the same result
type; CASPT2 stays specified (see above), never built here.
"""

from __future__ import annotations

from itertools import combinations
from typing import NamedTuple

import numpy as np

from atomterm.detbasis import (
    determinant_basis,
    operator_apply,
    slater_condon_matrix,
)

__all__ = [
    "PT2Result",
    "fois_indices",
    "diagonal_energies",
    "epstein_nesbet",
    "epstein_nesbet_dense",
]


class PT2Result(NamedTuple):
    """One PT2 evaluation: the reference energy it corrected beside
    the correction and its meters.

    e0 : the recomputed reference energy ``<Psi|H|Psi>`` over the CAS
        (the module's own ruler; re-derived from the CI, not trusted
        from the caller).
    e2 : the second-order correction ``sum_mu |<mu|H|Psi>|^2 /
        (E0 - H0_mu_mu)``.
    floor : ``min |E0 - H0_mu_mu|`` over the coupled FOIS
        (``inf`` when the FOIS is empty -- no denominators, no
        intruders possible).
    w_ref : the reference weight ``1 / (1 + sum |C1|^2)``.
    n_fois : the coupled FOIS cardinality.
    """

    e0: float
    e2: float
    floor: float
    w_ref: float
    n_fois: int


def _cas_mask(dets: list[tuple[int, ...]], n_val: int,
              n_act: int) -> np.ndarray:
    """Which determinants lie entirely inside the active columns."""
    inside = [
        all(o < n_act or n_val <= o < n_val + n_act for o in det)
        for det in dets
    ]
    return np.array(inside, dtype=bool)


def _fois_brute(n_val: int, na: int, nb: int,
                n_act: int) -> np.ndarray:
    """The brute-force coupling-set enumeration: every non-CAS
    determinant within two spin-orbital substitutions of some CAS
    determinant. The completeness certificate -- the production
    enumeration (the exact nonzero pattern of the operator pair)
    coincides with this when the CI has full CAS support (generic).
    """
    dets = determinant_basis(n_val, na, nb)
    index = {d: k for k, d in enumerate(dets)}
    n_s = 2 * n_val
    found: set[int] = set()
    cas = set(d for d in dets
              if all(o < n_act or n_val <= o < n_val + n_act for o in d))
    for ref in cas:
        occ = list(ref)
        unocc = [k for k in range(n_s) if k not in occ]
        for k_sub in (1, 2):
            for removed in combinations(occ, k_sub):
                for added in combinations(unocc, k_sub):
                    kept = [o for o in occ if o not in removed]
                    det = tuple(sorted(kept + list(added)))
                    # spin-preserving: an alpha slot is refilled by an
                    # alpha spin-orbital, a beta by a beta (the sector
                    # (na, nb) never changes)
                    same_spin = (
                        sum(r < n_val for r in removed)
                        == sum(a < n_val for a in added))
                    if det not in cas and same_spin:
                        found.add(index[det])
    return np.array(sorted(found), dtype=np.int64)


def fois_indices(n_val: int, na: int, nb: int, n_act: int) -> np.ndarray:
    """The FOIS as brute-force determinant indices (rung 0).

    Every non-CAS determinant within two spin-orbital substitutions
    of some CAS determinant -- the Slater-Condon reach of the
    (one-body, two-body) operator class, spin-preserving (the sector
    (na, nb) never changes). The completeness certificate: the
    production coupled pattern equals this when the CI has full CAS
    support (generic couplings). See :func:`_fois_brute` (the body).
    """
    return _fois_brute(n_val, na, nb, n_act)


def diagonal_energies(dets: list[tuple[int, ...]], h1: np.ndarray,
                      g: np.ndarray) -> np.ndarray:
    """``H_mu_mu`` by the explicit occupation sum -- the independent
    diagonal construction.

    ``H_mu_mu = sum_p h[p, p] + 1/2 sum_{p<q} (G[p, q, p, q]
    + G[q, p, q, p] - G[q, p, p, q] - G[p, q, q, p])`` over the
    occupied spin-orbitals -- the ANTISYMMETRIZED pair sum, no
    permutational symmetry of ``g`` assumed (the symmetric direct
    form would be wrong on general arrays; random non-symmetric
    integrals catch it). Plain index algebra on the occupation
    tuples, no pair-classification machinery. Pinned elementwise
    against the Slater-Condon diagonal; rung 2 (the Dyall diagonal)
    reuses the pattern.
    """
    dtype = np.result_type(h1, g)
    out = np.zeros(len(dets), dtype=dtype)
    for k, det in enumerate(dets):
        occ = np.asarray(det, dtype=np.int64)
        e = h1[occ, occ].sum()
        if len(occ) > 1:
            i, j = np.triu_indices(len(occ), k=1)
            p, q = occ[i], occ[j]
            e = e + (0.5 * (g[p, q, p, q] + g[q, p, q, p]
                            - g[q, p, p, q] - g[p, q, q, p])).sum()
        out[k] = e
    return out


def epstein_nesbet(h1: np.ndarray, g: np.ndarray, n_act: int,
                   na: int, nb: int, ci: np.ndarray) -> PT2Result:
    """The Epstein-Nesbet E(2) (rung 1, production construction).

    ``H0 = diag(H)`` in the external space; the correction
    ``E2 = sum_mu |<mu|H|Psi>|^2 / (E0 - H_mu_mu)`` over the coupled
    FOIS. Couplings come from the matrix-free operator application
    (the exact nonzero pattern); diagonals from
    :func:`diagonal_energies`; ``E0`` is re-derived from the CI over
    the CAS. The first-order amplitudes are the diagonal solve
    ``C1_mu = <mu|H|Psi> / (E0 - H_mu_mu)`` -- the meters read
    ``floor`` and ``w_ref`` off them.

    Parameters
    ----------
    h1, g : the operator pair over the VALENCE space (the folded-core
        field in ``h1``; active-first columns).
    n_act : the active-column count (the valence split).
    na, nb : the sector (excitations preserve it).
    ci : the reference CI over the CAS determinants, detbasis order
        (``determinant_basis(n_act, na, nb)`` -- the active-first
        relabeling is the identity).

    Returns
    -------
    :class:`PT2Result`.

    Raises
    ------
    ValueError
        On an exactly vanishing denominator: the partition is
        degenerate -- a zero EN denominator is physics the meters
        must surface, never a numerical accident to divide through.
    """
    n_val = h1.shape[0] // 2
    dets = determinant_basis(n_val, na, nb)
    cas_mask = _cas_mask(dets, n_val, n_act)
    cas_idx = np.nonzero(cas_mask)[0]
    if np.count_nonzero(ci) == 0:
        raise ValueError("the reference CI is identically zero")

    v = np.zeros(len(dets), dtype=np.result_type(h1, g))
    if len(ci) != len(cas_idx):
        raise ValueError(
            f"the CI length {len(ci)} does not match the CAS sector "
            f"({len(cas_idx)} determinants over n_act={n_act}, "
            f"({na}, {nb}))")
    v[cas_idx] = ci
    hv = operator_apply(dets, one_body=h1, two_body=g)(v)
    e0 = np.vdot(ci, hv[cas_idx])

    fois_idx = np.nonzero(~cas_mask & (hv != 0))[0]
    fois_dets = [dets[k] for k in fois_idx]
    couplings = hv[fois_idx]
    diag = diagonal_energies(fois_dets, h1, g)
    denom = e0 - diag
    if len(denom) and np.any(denom == 0):
        raise ValueError(
            "a zero EN denominator: the partition is degenerate -- "
            "an external configuration sits exactly at the reference "
            "energy (the intruder the floor meter exists to surface)")
    c1 = couplings / denom
    e2 = np.vdot(couplings, c1)
    floor = float(np.min(np.abs(denom))) if len(denom) else float("inf")
    w_ref = 1.0 / (1.0 + float(np.sum(np.abs(c1) ** 2)))
    return PT2Result(e0=e0, e2=e2, floor=floor, w_ref=w_ref,
                     n_fois=int(len(fois_idx)))


def epstein_nesbet_dense(h1: np.ndarray, g: np.ndarray, n_act: int,
                         na: int, nb: int,
                         ci: np.ndarray) -> PT2Result:
    """The Epstein-Nesbet E(2), dense evaluation -- the elementwise
    twin of :func:`epstein_nesbet`.

    Every ingredient from one dense Slater-Condon matrix over the
    full valence sector: ``E0`` from the CAS block, the coupling
    column from the CAS-FOIS slice, the denominators from the
    diagonal -- no shared code path with the production construction
    (the pair classification vs the matrix-free enumeration vs the
    occupation-sum diagonal). Test-tier substrate: the dense matrix
    is quadratic in the sector; campaign sizes ride the production
    path.
    """
    n_val = h1.shape[0] // 2
    dets = determinant_basis(n_val, na, nb)
    cas_mask = _cas_mask(dets, n_val, n_act)
    cas_idx = np.nonzero(cas_mask)[0]
    if np.count_nonzero(ci) == 0:
        raise ValueError("the reference CI is identically zero")

    h_full = slater_condon_matrix(dets, one_body=h1, two_body=g)
    e0 = np.vdot(ci, h_full[cas_idx][:, cas_idx] @ ci)
    fois_idx = np.nonzero(~cas_mask)[0]
    couplings = h_full[fois_idx][:, cas_idx] @ ci
    coupled = np.nonzero(couplings != 0)[0]
    fois_idx = fois_idx[coupled]
    couplings = couplings[coupled]
    diag = np.diag(h_full)[fois_idx]
    denom = e0 - diag
    if len(denom) and np.any(denom == 0):
        raise ValueError(
            "a zero EN denominator: the partition is degenerate -- "
            "an external configuration sits exactly at the reference "
            "energy (the intruder the floor meter exists to surface)")
    c1 = couplings / denom
    e2 = np.vdot(couplings, c1)
    floor = float(np.min(np.abs(denom))) if len(denom) else float("inf")
    w_ref = 1.0 / (1.0 + float(np.sum(np.abs(c1) ** 2)))
    return PT2Result(e0=e0, e2=e2, floor=floor, w_ref=w_ref,
                     n_fois=int(len(fois_idx)))
